const isLocale = (value: string | undefined): value is AppLocale =>
  value === 'en' || value === 'ka';

void i18n.use(initReactI18next).init({
  resources: {
    en: { translation: english },
    ka: { translation: georgian }
  },
  lng: typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('ka') ? 'ka' : 'en',
  fallbackLng: 'en',
  interpolation: { escapeValue: false },
  returnNull: false
});

export { i18n, isLocale };

export async function restoreLocalePreference(): Promise<AppLocale> {
  const saved = await db.settings.get('locale');
  if (isLocale(saved?.value)) return saved.value;
  return typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('ka')
    ? 'ka'
    : 'en';
}

export async function saveLocalePreference(locale: AppLocale): Promise<void> {
  await db.settings.put({
    key: 'locale',
    value: locale,
    updatedAt: new Date().toISOString()
  });
  await i18n.changeLanguage(locale);
}
